// K5 · RENDER THE EVIDENCE CHECKLIST FROM THE GOVERNED CATALOGUE.
//
// PURE. No argv, no filesystem, no clock — so the claim "the committed document matches the code" is
// falsifiable by a test rather than by running a command and looking. The command is `emit.ts`, which
// holds the I/O and nothing else.
//
// WHY RENDERED AND NOT WRITTEN. An artefact that leaves the repository is verified by the code it
// describes, never by a bespoke read-through: a hand-authored checklist drifts from the lifecycle
// silently and whoever performs the ceremony discovers it afterwards. The same rule the pilot-intake
// package was built on, for the same reason.
import {
  K5_EVIDENCE_CATALOGUE_VERSION,
  K5_EVIDENCE_ITEMS,
  k5HonestStatement,
  k5MechanicallyVerifiableConditions,
  type K5Checkability,
  type K5Condition,
} from "../../src/contract/k5EvidenceCatalogue";

const CONDITION_TITLE: Readonly<Record<K5Condition, string>> = Object.freeze({
  channelIndependentlyVerified: "C1 · the channel is the institution's own, found independently",
  institutionIdentityVerified: "C2 · the institution is who it says it is",
  keyControlDemonstrated: "C3 · the responder controls the key being registered",
  ceremonyRecorded: "C4 · the ceremony is recorded, by two identities",
});

const CHECKABILITY_LABEL: Readonly<Record<K5Checkability, string>> = Object.freeze({
  CORROBORATED: "**NH VERIFIES THIS** — mechanically, from the artefact",
  WELL_FORMED: "NH checks it is PRESENT AND COMPLETE — not that it is true",
  UNCORROBORATED_CLAIM: "NH RECORDS IT AND ESTABLISHES NOTHING — a human verification",
});

export function renderK5Checklist(): string {
  const order: readonly K5Condition[] = [
    "channelIndependentlyVerified",
    "institutionIdentityVerified",
    "keyControlDemonstrated",
    "ceremonyRecorded",
  ];
  const lines: string[] = [];

  lines.push("# K5 · evidence checklist for registering a real institution's signing key");
  lines.push("");
  lines.push(
    "> **GENERATED FROM `src/contract/k5EvidenceCatalogue.ts`. Do not edit this file.** A test asserts " +
      "it matches the catalogue byte for byte, because a checklist written beside the code drifts from " +
      "it silently and the drift is discovered during the ceremony.",
  );
  lines.push("");
  lines.push(`Catalogue version: \`${K5_EVIDENCE_CATALOGUE_VERSION}\``);
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push("## What four green booleans actually mean");
  lines.push("");
  lines.push(`> ${k5HonestStatement()}`);
  lines.push("");
  lines.push(
    "`keyMayBeActivated` refuses to activate a key until all four conditions are claimed, and " +
      "`keyRegistrationRefusals` returns **every** unmet one rather than the first — so a registration " +
      "blocked on two grounds says so. But the booleans arrive from the NH operator and the server " +
      "validates only that they are `true`. The register's integrity is strong; **its input is a human " +
      "claim**, and a pilot brief presenting four ticks as four verified facts would overstate exactly " +
      "what this checklist exists to prevent.",
  );
  lines.push("");
  lines.push(
    `Mechanically verifiable conditions: **${k5MechanicallyVerifiableConditions().join(", ") || "none"}**.`,
  );
  lines.push("");
  lines.push("---");
  lines.push("");

  for (const condition of order) {
    const items = K5_EVIDENCE_ITEMS.filter((i) => i.supports === condition);
    lines.push(`## ${CONDITION_TITLE[condition]}`);
    lines.push("");
    lines.push(`Governed field: \`${condition}\``);
    lines.push("");
    for (const item of items) {
      lines.push(`### ${item.id}`);
      lines.push("");
      lines.push(`- **Collect:** ${item.artefact}`);
      lines.push(`- **Issued by:** ${item.issuedBy}`);
      lines.push(`- **NH's position:** ${CHECKABILITY_LABEL[item.checkability]}`);
      lines.push(`- **Why this and not something cheaper:** ${item.why}`);
      lines.push(`- **Does NOT establish:** ${item.doesNotEstablish}`);
      lines.push("");
    }
    lines.push("---");
    lines.push("");
  }

  lines.push("## What is still blocked after every item above is collected");
  lines.push("");
  lines.push(
    "Nothing here reaches `AUTHORITY_VERIFIED`. That rung means *evidenced by a channel the beneficiary " +
      "cannot unilaterally alter*, and this ceremony is performed and recorded by the submitting side. " +
      "The four channels that would reach it — a signed export, a fetch NH performs itself, a " +
      "machine-issued system-of-record attestation, and third-party reconciliation — are unbuilt, and " +
      "only the last has a corroborating party that is not party to the claim.",
  );
  lines.push("");
  lines.push(
    "**And the item this checklist cannot supply:** if an institution will not sign an attestation at " +
      "all, there is no externally attested settlement and the correct output is **no PROVEN claim** — " +
      "not a lower confidence, not a provisional proof. Claimed revenue is not proven revenue.",
  );
  lines.push("");
  return `${lines.join("\n")}`;
}
